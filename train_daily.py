#!/usr/bin/env python3
"""Oga daily trainer: reads the self-learning logs, finds what the built-in
brain could not answer, generates candidate new knowledge topics, and
commits them to the oga-learning branch. NEVER pushes to main.

Usage:
  python3 train_daily.py                  # full run (dry validation + commit to oga-learning)
  python3 train_daily.py --dry-run        # read logs, show groups, no file changes, no commit
  python3 train_daily.py --fixture PATH   # read fixture logs (JSON) instead of the real db (for tests)

SAFETY:
  - This script refuses to run on main/master: it must checkout oga-learning.
  - It never pushes, never merges, and never touches main.
  - Without GEMINI_API_KEY it writes a plain TODO list (LEARNING_TODO.md)
    and never invents content.
  - With GEMINI_API_KEY it asks Gemini for short, static knowledge entries,
    but still only writes them to learned_topics.py on oga-learning, run
    through the test batteries before commit. Nothing goes live without
    the owner merging oga-learning into main by hand.

Render free-tier caveat: the learning db lives in /tmp and therefore
survives only until the next deploy/restart. If the db is empty after a
restart, the trainer reports "no data" and does nothing (see LEARNING_LOOP.md).
"""
import argparse
import ast
import collections
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

LEARNING_BRANCH = "oga-learning"
PROTECTED_BRANCHES = {"main", "master"}


def _git(*args):
    return subprocess.run(
        ["git"] + list(args), capture_output=True, text=True
    )


def guard_branch():
    """Refuse to run on main/master; require the learning branch."""
    r = _git("rev-parse", "--abbrev-ref", "HEAD")
    branch = (r.stdout or "").strip()
    if branch in PROTECTED_BRANCHES or branch == "HEAD":
        raise SystemExit(
            f"Refusing to run on {branch or 'detached HEAD'}: train_daily.py "
            f"only runs on {LEARNING_BRANCH}, and never pushes to main."
        )
    if branch != LEARNING_BRANCH:
        raise SystemExit(
            f"Current branch is '{branch}'. Run: git checkout {LEARNING_BRANCH}"
        )
    return branch


def load_logs(fixture_path):
    """Return (questions, terminal_events) from a fixture or the real db."""
    if fixture_path:
        try:
            data = json.loads(open(fixture_path).read())
            return data.get("questions", []), data.get("terminal_events", [])
        except Exception:
            return [], []
    import learning_log
    return learning_log.read_all()


def normalize_question(q):
    q = re.sub(r"\s+", " ", (q or "").strip().lower())
    q = q.strip(" .!?")
    return q


def group_gaps(questions):
    """Group fallback/unanswered questions by normalized form."""
    groups = collections.Counter()
    examples = {}
    for row in questions:
        try:
            fell = int(row.get("fell_back", 0))
        except Exception:
            fell = 0
        q = normalize_question(row.get("question", ""))
        if not q:
            continue
        if fell or row.get("answer_path") == "built-in-fallback":
            groups[q] += 1
            examples[q] = q
    return groups, examples


def group_terminal_errors(events):
    """Group common terminal errors by command root + error essence."""
    groups = collections.Counter()
    for row in events:
        if row.get("kind") != "error":
            continue
        cmd = (row.get("command") or "").strip()
        root = cmd.split()[0] if cmd else "unknown"
        out = re.sub(r"\s+", " ", (row.get("output_snippet") or "")).strip()[:80]
        groups[(root, out)] += 1
    return groups


def write_todo(question_groups, terminal_groups, nc, ne):
    lines = [
        "# Oga learning TODO (generated by train_daily.py, no GEMINI_API_KEY)",
        "",
        f"Unanswered questions grouped: {nc} distinct. Common terminal",
        f"errors: {ne} distinct patterns.",
        "",
        "## Questions the built-in brain fell back on (most frequent first)",
    ]
    for q, n in question_groups.most_common(30):
        lines.append(f"- ({n}x) {q}")
    lines += ["", "## Common terminal errors (most frequent first)"]
    for (root, out), n in terminal_groups.most_common(30):
        lines.append(f"- ({n}x) `{root}` : {out}")
    lines += [
        "",
        "Owner/trainer: add answers to learned_topics.py or approve GEMINI_API_KEY",
        "to let the trainer generate candidates automatically.",
    ]
    open("LEARNING_TODO.md", "w").write("\n".join(lines) + "\n")


def parse_topics_file(path):
    try:
        tree = ast.parse(open(path).read())
    except Exception:
        return []
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == "LEARNED_TOPICS":
                    try:
                        return ast.literal_eval(node.value)
                    except Exception:
                        return []
    return []


def write_topics_file(path, topics):
    header = (
        '"""Topics learned by the daily trainer (train_daily.py).\n'
        "\n"
        "Each entry is (keyword phrase, answer body) and is merged into the\n"
        "built-in brain in cyberlord_ai.py at import time. The main persona\n"
        "checks these after the built-in knowledge topics, so learned topics\n"
        "fill gaps (questions that fell back to \"I don't know\") without\n"
        "overriding existing knowledge. Never put secrets, personal data or\n"
        "time-sensitive figures (prices, news) here; the trainer only adds\n"
        "stable, general knowledge.\n"
        '"""\n'
    )
    with open(path, "w") as fh:
        fh.write(header)
        fh.write("LEARNED_TOPICS = [\n")
        for k, v in topics:
            fh.write("    (\n        " + repr(k) + ",\n        " + repr(v) + ",\n    ),\n")
        fh.write("]\n")


def ask_gemini(topic_lines, daily_limit=5):
    """Ask Gemini for candidate static-knowledge entries. Returns list of
    (key, body) string pairs, or [] on any failure. Never raises."""
    key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not key or not topic_lines:
        return []
    prompt = (
        "You are Oga's daily trainer. Below are questions the built-in CyberLord "
        "brain could not answer (fell back to 'I don't know') and common academy "
        "terminal errors. For each, output ONE short static knowledge entry as a "
        "Python tuple ('keyword phrase', 'answer body'). Rules: only stable general "
        "knowledge, no prices, no news, no personal data, no secrets; keep each "
        "answer under 500 characters and beginner-friendly; answer in a warm human "
        "tone; skip anything you do not know. Output ONLY valid Python tuples, one "
        "per line, no markdown, no numbering.\n\n"
        + "\n".join(topic_lines[:2000])
    )
    try:
        import requests
        model = os.environ.get("GEMINI_MODEL", "gemini-3.5-flash-lite").strip() or "gemini-3.5-flash-lite"
        resp = requests.post(
            f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent",
            headers={"Content-Type": "application/json", "x-goog-api-key": key},
            json={"contents": [{"role": "user", "parts": [{"text": prompt}]}],
                  "generationConfig": {"temperature": 0.3, "maxOutputTokens": 2000}},
            timeout=60,
        )
        resp.raise_for_status()
        data = resp.json()
        cands = data.get("candidates") or []
        parts = ((cands[0].get("content") or {}).get("parts") or []) if cands else []
        text = "\n".join(p.get("text", "") for p in parts if isinstance(p, dict)).strip()
    except Exception:
        return []
    out = []
    for line in text.splitlines():
        line = line.strip().strip("`")
        if not line.startswith("("):
            continue
        try:
            val = ast.literal_eval(line)
            if (isinstance(val, tuple) and len(val) == 2
                    and isinstance(val[0], str) and isinstance(val[1], str)
                    and val[0].strip() and 20 <= len(val[1]) <= 1200):
                out.append((val[0].strip()[:120], val[1].strip()))
        except Exception:
            continue
    return out[:daily_limit]


def run_batteries():
    """Run the test batteries; returns (ok, output tail)."""
    outputs = []
    ok = True
    for script in ("test_learning_loop.py", "test_academy.py", "test_brand_toyota.py",
                   "test_personas.py"):
        if not os.path.exists(script):
            continue
        r = subprocess.run([sys.executable, script], capture_output=True, text=True, timeout=600)
        tail = (r.stdout or "")[-400:]
        outputs.append(f"== {script} -> {r.returncode}\n{tail}")
        if r.returncode != 0:
            ok = False
            break
    return ok, "\n".join(outputs)


def commit_to_learning_branch(changed):
    """Commit changed files to the learning branch. NEVER pushes to main."""
    _git("checkout", LEARNING_BRANCH)
    for f in changed:
        if os.path.exists(f):
            _git("add", f)
    _git("commit", "-m", "oga learning: " + ", ".join(changed))
    # push ONLY the learning branch (never main)
    push = _git("push", "origin", LEARNING_BRANCH)
    return push.returncode == 0, (push.stdout + push.stderr)[-400:]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--fixture", default="")
    args = ap.parse_args()

    if not args.dry_run and not args.fixture:
        guard_branch()

    questions, events = load_logs(args.fixture or None)
    q_groups, _ = group_gaps(questions)
    t_groups = group_terminal_errors(events)
    nc = len(q_groups)
    ne = len(t_groups)

    if args.dry_run:
        print(f"[dry-run] questions: {len(questions)}, terminal events: {len(events)}")
        print(f"[dry-run] unanswered groups: {nc}, terminal-error patterns: {ne}")
        for q, n in q_groups.most_common(10):
            print(f"  Q ({n}x) {q}")
        for (root, out), n in t_groups.most_common(10):
            print(f"  T ({n}x) {root}: {out}")
        print("[dry-run] no files changed, no commit")
        return 0

    if nc == 0 and ne == 0:
        print("No unanswered questions or terminal errors to learn from. Nothing to do.")
        return 0

    if not os.environ.get("GEMINI_API_KEY", "").strip():
        write_todo(q_groups, t_groups, nc, ne)
        print(f"Wrote LEARNING_TODO.md ({nc} question groups, {ne} terminal patterns). No Gemini key, so nothing merged.")
        return 0

    topic_lines = [f"Q: {q}" for q, _ in q_groups.most_common(30)]
    topic_lines += [f"T: {root}: {out}" for (root, out), _ in t_groups.most_common(30)]
    candidates = ask_gemini(topic_lines)
    if not candidates:
        write_todo(q_groups, t_groups, nc, ne)
        print("Gemini produced no usable candidates; wrote LEARNING_TODO.md instead.")
        return 0

    existing = parse_topics_file("learned_topics.py")
    known = {(k.lower() if isinstance(k, str) else k) for k, _ in existing}
    merged = list(existing)
    for k, v in candidates:
        if k.lower() not in known:
            merged.append((k, v))
            known.add(k.lower())
    write_topics_file("learned_topics.py", merged)

    ok, output = run_batteries()
    if not ok:
        print("Test batteries FAILED; learned topics NOT committed:\n" + output)
        return 1
    pushed, push_output = commit_to_learning_branch(["learned_topics.py", "LEARNING_TODO.md"] if os.path.exists("LEARNING_TODO.md") else ["learned_topics.py"])
    print(f"Merged {len(candidates)} topics into learned_topics.py, batteries green. Pushed oga-learning: {pushed}")
    print(push_output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
